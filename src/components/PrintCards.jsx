// ---------------------------------------------------------------------------
// Лист А4 с карточками нужного типа. cards: [{ sn, pn, hw, date, material, qrUrl }]
// ---------------------------------------------------------------------------
export function CardsSheet({ prefix, cards }) {
    const type = getCardType(prefix);

    return (
        <div className='print-sheet-wrapper'>
            <div className={`print-sheet print-sheet--${type}`}>
                {cards.map((card) => {
                    if (type === 'tablet')
                        return <CardTablet key={card.sn} {...card} />;
                    if (type === 'dock')
                        return <CardDockStation key={card.sn} {...card} />;
                    return <CardDisplayFront key={card.sn} {...card} />;
                })}
            </div>
        </div>
    );
}
