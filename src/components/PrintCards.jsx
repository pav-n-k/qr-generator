// ---------------------------------------------------------------------------
// Какой тип карточки соответствует какому S/N Prefix
// ---------------------------------------------------------------------------
const TABLET_PREFIXES = ['TCR', 'TCN', 'TSR', 'TSN'];
const DOCK_PREFIXES = ['DCR', 'DSR'];

export function getCardType(prefix) {
    if (TABLET_PREFIXES.includes(prefix)) return 'tablet';
    if (DOCK_PREFIXES.includes(prefix)) return 'dock';
    if (prefix === 'DCF') return 'display';
    return 'tablet';
}

// Материал указывается на карточке только для DCF / DCR / DSR
// (для TCR/TCN/TSR/TSN на карточке материала нет — см. скриншот 1)
export const MATERIAL_BY_PREFIX = {
    DCF: 'PC SABIC EXL9330',
    DCR: 'LYPOY EF1006FS',
    DSR: 'PC TAIRILOY AC3100',
};

// ---------------------------------------------------------------------------
// Физические размеры карточек (мм) — см. скриншоты 1/2/3
// ---------------------------------------------------------------------------
export const CARD_SIZES_MM = {
    tablet: { width: 45.5, height: 13.5 }, // скриншот 1: TCR/TCN/TSR/TSN
    dock: { width: 30, height: 20 }, // скриншот 2: DCR/DSR
    display: { width: 60, height: 40 }, // скриншот 3: DCF
};

// ---------------------------------------------------------------------------
// Сколько карточек данного типа помещается на один лист А4 при печати
// (те же поля margin/gap заданы в PrintCards.css в блоке @page/.print-sheet —
// если поменяете их там, обновите и здесь)
// ---------------------------------------------------------------------------
const PAGE_WIDTH_MM = 210;
const PAGE_HEIGHT_MM = 297;
const PAGE_MARGIN_MM = 5;
const CARD_GAP_MM = 1;

export function getMaxCardsPerSheet(prefix) {
    const type = getCardType(prefix);
    const { width, height } = CARD_SIZES_MM[type];
    const usableWidth = PAGE_WIDTH_MM - PAGE_MARGIN_MM * 2;
    const usableHeight = PAGE_HEIGHT_MM - PAGE_MARGIN_MM * 2;

    const cols = Math.max(
        1,
        Math.floor((usableWidth + CARD_GAP_MM) / (width + CARD_GAP_MM)),
    );
    const rows = Math.max(
        1,
        Math.floor((usableHeight + CARD_GAP_MM) / (height + CARD_GAP_MM)),
    );

    return { type, cols, rows, max: cols * rows };
}

// ---------------------------------------------------------------------------
// YYYY-MM-DD -> DD.MM.YY (как на скриншотах)
// ---------------------------------------------------------------------------
function formatDateShort(isoDate) {
    if (!isoDate) return '';
    const [y, m, d] = isoDate.split('-');
    if (!y || !m || !d) return isoDate;
    return `${d}.${m}.${y.slice(2)}`;
}

